"""API-key authentication, roles and rate limiting.

Keys are random 256-bit tokens generated by ``aml-sentinel new-api-key``. The server
is configured only with their SHA-256 digests (``API_KEYS=user:role:<hex>,...``), so a
leaked ``.env`` does not leak usable credentials. A fast hash is adequate here because
the keys are high-entropy random values, not human passwords.

Security:
    * A presented key is compared with **every** configured digest using
      :func:`hmac.compare_digest`, with no early exit, so response time does not
      reveal which entry, if any, matched.
    * Roles are ordered: ``admin`` can do everything ``analyst`` can.
    * Failed authentication is rate-limited per client address, which slows key
      guessing; successful requests are limited per user.
"""

from __future__ import annotations

import hashlib
import hmac
import re
import secrets
import threading
import time
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from enum import StrEnum
from typing import Final

from aml_sentinel.exceptions import ConfigurationError

KEY_PREFIX: Final = "amls_"
MAX_KEY_LENGTH: Final = 256
# Same alphabet as audit-log actors, so every user id can be recorded verbatim.
_USER_RE: Final = re.compile(r"^[A-Za-z0-9_.@-]{1,64}$")
_DIGEST_RE: Final = re.compile(r"^[0-9a-f]{64}$")


class Role(StrEnum):
    """API roles, lowest privilege first."""

    ANALYST = "analyst"
    ADMIN = "admin"


_RANK: Final = {Role.ANALYST: 1, Role.ADMIN: 2}


@dataclass(frozen=True, slots=True)
class Principal:
    """An authenticated caller.

    Attributes:
        user: User id (recorded in the audit log).
        role: Granted role.
    """

    user: str
    role: Role

    def has(self, required: Role) -> bool:
        """Whether this principal holds ``required`` or a higher role.

        Args:
            required: Minimum role.

        Returns:
            True if allowed.
        """
        return _RANK[self.role] >= _RANK[required]


@dataclass(frozen=True, slots=True)
class _KeyEntry:
    user: str
    role: Role
    digest: bytes


def generate_api_key() -> str:
    """Create a new random API key.

    Returns:
        ``amls_`` followed by 43 URL-safe characters (256 bits of entropy).
    """
    return KEY_PREFIX + secrets.token_urlsafe(32)


def hash_api_key(key: str) -> str:
    """Digest stored in ``API_KEYS`` for a key.

    Args:
        key: Plaintext key.

    Returns:
        Lower-case hex SHA-256.
    """
    return hashlib.sha256(key.encode("utf-8")).hexdigest()


class ApiKeyStore:
    """Configured credentials.

    Args:
        entries: Parsed key entries.

    Raises:
        ConfigurationError: If no entries are given.
    """

    def __init__(self, entries: Sequence[_KeyEntry]) -> None:
        if not entries:
            raise ConfigurationError("API_KEYS has no entries")
        self._entries = tuple(entries)

    @classmethod
    def parse(cls, spec: str | None) -> ApiKeyStore:
        """Parse ``user:role:sha256hex`` entries separated by commas.

        Args:
            spec: Value of ``API_KEYS``.

        Returns:
            The key store.

        Raises:
            ConfigurationError: If the value is missing or malformed. Messages name
                the entry position only, never its content.
        """
        if spec is None or not spec.strip():
            raise ConfigurationError(
                "API_KEYS is required to start the API; create keys with "
                "`aml-sentinel new-api-key --user <id> --role analyst|admin`"
            )
        entries: list[_KeyEntry] = []
        for n, raw in enumerate(spec.split(","), start=1):
            parts = raw.strip().split(":")
            if len(parts) != 3:
                raise ConfigurationError(f"API_KEYS entry {n} is not user:role:sha256hex")
            user, role, digest = parts
            if not _USER_RE.match(user) or role not in set(Role):
                raise ConfigurationError(f"API_KEYS entry {n} has an invalid user or role")
            if not _DIGEST_RE.match(digest):
                raise ConfigurationError(f"API_KEYS entry {n} digest must be 64 hex chars")
            entries.append(_KeyEntry(user, Role(role), bytes.fromhex(digest)))
        if len({e.user for e in entries}) != len(entries):
            raise ConfigurationError("API_KEYS lists a user more than once")
        if len({e.digest for e in entries}) != len(entries):
            raise ConfigurationError("API_KEYS reuses one key for several users")
        return cls(entries)

    def authenticate(self, presented: str | None) -> Principal | None:
        """Resolve a presented key to a principal.

        Args:
            presented: Value of the ``X-API-Key`` header.

        Returns:
            The principal, or ``None`` if the key is missing or unknown.
        """
        if not presented or len(presented) > MAX_KEY_LENGTH:
            return None
        digest = hashlib.sha256(presented.encode("utf-8")).digest()
        match: _KeyEntry | None = None
        for entry in self._entries:
            if hmac.compare_digest(digest, entry.digest):
                match = entry
        return None if match is None else Principal(match.user, match.role)


class RateLimiter:
    """Token-bucket rate limiter keyed by caller.

    Args:
        per_minute: Sustained requests per minute; also the burst size.
        clock: Monotonic clock in seconds (injectable for tests).
        max_keys: Bound on tracked callers; idle full buckets are evicted first.
    """

    def __init__(
        self,
        per_minute: int,
        *,
        clock: Callable[[], float] = time.monotonic,
        max_keys: int = 10_000,
    ) -> None:
        self._capacity = float(per_minute)
        self._rate = per_minute / 60.0
        self._clock = clock
        self._max_keys = max_keys
        self._buckets: dict[str, tuple[float, float]] = {}
        self._lock = threading.Lock()

    def _level(self, key: str, now: float) -> float:
        tokens, last = self._buckets.get(key, (self._capacity, now))
        return min(self._capacity, tokens + (now - last) * self._rate)

    def allow(self, key: str) -> tuple[bool, float]:
        """Consume one token for ``key`` if available.

        Args:
            key: Caller identity, e.g. ``user:alice`` or ``ip:127.0.0.1``.

        Returns:
            ``(allowed, retry_after_seconds)``.
        """
        with self._lock:
            now = self._clock()
            if key not in self._buckets and len(self._buckets) >= self._max_keys:
                self._evict(now)
            tokens = self._level(key, now)
            if tokens >= 1.0:
                self._buckets[key] = (tokens - 1.0, now)
                return True, 0.0
            self._buckets[key] = (tokens, now)
            return False, (1.0 - tokens) / self._rate

    def _evict(self, now: float) -> None:
        full = [k for k in self._buckets if self._level(k, now) >= self._capacity]
        for k in full or list(self._buckets)[: max(1, len(self._buckets) // 10)]:
            del self._buckets[k]
