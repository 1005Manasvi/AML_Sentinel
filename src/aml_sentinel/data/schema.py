"""Schema of the IBM AMLworld transaction data.

Two representations exist on purpose:

* Column constants and value sets used to validate *bulk* DataFrames vectorially
  (millions of rows; per-row pydantic validation would be far too slow).
* Pydantic models for *single* untrusted records arriving at the API boundary.

Security note:
    Bank codes and account IDs are restricted to short alphanumeric strings so that
    data fields cannot smuggle markup or prompt-injection payloads into downstream
    summaries and dashboards.
"""

from __future__ import annotations

from datetime import datetime
from enum import StrEnum
from typing import Final, Literal, get_args

from pydantic import BaseModel, ConfigDict, Field

TIMESTAMP_FORMAT: Final = "%Y/%m/%d %H:%M"

# Exact header of the *_Trans.csv files. Note the duplicated "Account" column
# (sender, then receiver): the loader must rename by position, not by name.
RAW_HEADER: Final = (
    "Timestamp",
    "From Bank",
    "Account",
    "To Bank",
    "Account",
    "Amount Received",
    "Receiving Currency",
    "Amount Paid",
    "Payment Currency",
    "Payment Format",
    "Is Laundering",
)


class Col(StrEnum):
    """Canonical column names used everywhere downstream of the loader."""

    TX_ID = "tx_id"
    TIMESTAMP = "timestamp"
    FROM_BANK = "from_bank"
    FROM_ACCOUNT = "from_account"
    TO_BANK = "to_bank"
    TO_ACCOUNT = "to_account"
    AMOUNT_RECEIVED = "amount_received"
    RECEIVING_CURRENCY = "receiving_currency"
    AMOUNT_PAID = "amount_paid"
    PAYMENT_CURRENCY = "payment_currency"
    PAYMENT_FORMAT = "payment_format"
    IS_LAUNDERING = "is_laundering"
    FROM_ID = "from_id"
    TO_ID = "to_id"
    AMOUNT_PAID_USD = "amount_paid_usd"
    AMOUNT_RECEIVED_USD = "amount_received_usd"


# Positional mapping of RAW_HEADER onto canonical names.
RAW_COLUMNS: Final = (
    Col.TIMESTAMP,
    Col.FROM_BANK,
    Col.FROM_ACCOUNT,
    Col.TO_BANK,
    Col.TO_ACCOUNT,
    Col.AMOUNT_RECEIVED,
    Col.RECEIVING_CURRENCY,
    Col.AMOUNT_PAID,
    Col.PAYMENT_CURRENCY,
    Col.PAYMENT_FORMAT,
    Col.IS_LAUNDERING,
)

Currency = Literal[
    "US Dollar",
    "Euro",
    "Swiss Franc",
    "Yuan",
    "Shekel",
    "Rupee",
    "UK Pound",
    "Yen",
    "Ruble",
    "Bitcoin",
    "Canadian Dollar",
    "Australian Dollar",
    "Mexican Peso",
    "Saudi Riyal",
    "Brazil Real",
]
PaymentFormat = Literal["Cheque", "Credit Card", "ACH", "Cash", "Reinvestment", "Wire", "Bitcoin"]

CURRENCIES: Final[frozenset[str]] = frozenset(get_args(Currency))
PAYMENT_FORMATS: Final[frozenset[str]] = frozenset(get_args(PaymentFormat))
USD: Final = "US Dollar"

_BANK_PATTERN: Final = r"^[0-9]{1,10}$"
_ACCOUNT_PATTERN: Final = r"^[0-9A-Za-z]{1,32}$"


class DatasetName(StrEnum):
    """Supported datasets (file name prefixes).

    ``SAMPLE`` is the small synthetic dataset generated by
    :mod:`aml_sentinel.data.synthetic` and bundled in ``data/sample/``; the others
    are IBM AMLworld downloads in ``data/raw/``.
    """

    HI_SMALL = "HI-Small"
    LI_SMALL = "LI-Small"
    SAMPLE = "Sample"


# Every supported dataset is synthetic (IBM AMLworld is simulated; Sample is ours).
# A real-data source must be added WITHOUT joining this set, which keeps it away from
# hosted third-party models such as Jev.
SYNTHETIC_DATASETS: Final[frozenset[DatasetName]] = frozenset(
    {DatasetName.HI_SMALL, DatasetName.LI_SMALL, DatasetName.SAMPLE}
)


def account_node_id(bank: str, account: str) -> str:
    """Build the graph node ID for an account.

    Account IDs are qualified by bank so that identical account strings at different
    banks can never be merged into one node.

    Args:
        bank: Bank code (string, leading zeros preserved).
        account: Account identifier.

    Returns:
        ``"<bank>:<account>"``.
    """
    return f"{bank}:{account}"


class Transaction(BaseModel):
    """A single, unlabeled transaction as received from an untrusted source.

    Attributes:
        timestamp: When the transaction happened (naive, dataset-local time).
        from_bank: Sender bank code.
        from_account: Sender account ID.
        to_bank: Receiver bank code.
        to_account: Receiver account ID.
        amount_received: Amount credited, in ``receiving_currency``.
        receiving_currency: Currency credited.
        amount_paid: Amount debited, in ``payment_currency``.
        payment_currency: Currency debited.
        payment_format: Payment channel.
    """

    model_config = ConfigDict(frozen=True, extra="forbid", str_strip_whitespace=True)

    timestamp: datetime
    from_bank: str = Field(pattern=_BANK_PATTERN)
    from_account: str = Field(pattern=_ACCOUNT_PATTERN)
    to_bank: str = Field(pattern=_BANK_PATTERN)
    to_account: str = Field(pattern=_ACCOUNT_PATTERN)
    amount_received: float = Field(ge=0, allow_inf_nan=False)
    receiving_currency: Currency
    amount_paid: float = Field(ge=0, allow_inf_nan=False)
    payment_currency: Currency
    payment_format: PaymentFormat


class LabeledTransaction(Transaction):
    """A transaction with its ground-truth laundering label (synthetic data only).

    Attributes:
        is_laundering: True if the simulator generated it as part of laundering.
    """

    is_laundering: bool
